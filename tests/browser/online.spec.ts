async function fakeBackend(page: Page, initialAvatar?: string, initial?: { documents: Document[]; revision: number; habits?: HabitData }) {
  let documents: Document[] = initial?.documents || []
  let revision = initial?.revision || 0
  let habitData: unknown = initial?.habits ?? null
  let habitRevision = initial?.habits ? 1 : 0
  let lastHabitOperation = ''
  let offline = false
  let lastOperation = ''
  let userMetadata: Record<string, unknown> = initialAvatar ? { avatar: initialAvatar } : {}
  await page.route('https://mock.invalid/**', async route => {
    if (offline) { await route.abort('internetdisconnected'); return }
    const request = route.request(); const path = new URL(request.url()).pathname
    if (request.method() === 'OPTIONS') { await route.fulfill({ status: 204, headers: { 'access-control-allow-origin': '*', 'access-control-allow-headers': '*', 'access-control-allow-methods': '*' } }); return }
    let body: unknown
    if (path === '/rest/v1/rpc/tor_online_recipe_read') body = { revision: 0, data: null }
    else if (path === '/rest/v1/rpc/tor_online_habit_read') body = { revision: habitRevision, data: habitData }
    else if (path === '/rest/v1/rpc/tor_online_habit_write') { const input = request.postDataJSON(); if (input.p_operation === lastHabitOperation) body = { status: 'ok', revision: habitRevision }; else if (input.p_revision !== habitRevision) body = { status: 'conflict' }; else { habitData = input.p_data; habitRevision++; lastHabitOperation = input.p_operation; body = { status: 'ok', revision: habitRevision } } }
    else if (path === '/rest/v1/rpc/tor_online_workout_read') body = { revision, documents }
    else if (path === '/rest/v1/rpc/tor_online_workout_write') {
      const input = request.postDataJSON()
      if (input.p_operation === lastOperation) body = { status: 'ok', revision }
      else if (input.p_revision !== revision) body = { status: 'conflict' }
      else { documents = input.p_documents; revision++; lastOperation = input.p_operation; body = { status: 'ok', revision } }
    } else if (path === '/auth/v1/user') { if (request.method() === 'PUT') userMetadata = { ...userMetadata, ...request.postDataJSON().data }; body = { id: owner, email: 'test@example.invalid', aud: 'authenticated', role: 'authenticated', user_metadata: userMetadata } }
    else { await route.abort(); throw new Error(`Unexpected mock API path: ${path}`) }
    await route.fulfill({ status: 200, contentType: 'application/json', headers: { 'access-control-allow-origin': '*' }, body: JSON.stringify(body) })
  })
  await page.addInitScript(({ id, avatar }) => {
    const user = { id, email: 'test@example.invalid', aud: 'authenticated', role: 'authenticated', user_metadata: avatar ? { avatar } : {} }
    const session = { access_token: 'fake-test-token', refresh_token: 'fake-test-refresh', token_type: 'bearer', expires_in: 3600, expires_at: Math.floor(Date.now() / 1000) + 3600, user }
    if (!localStorage.getItem('sb-mock-auth-token')) localStorage.setItem('sb-mock-auth-token', JSON.stringify(session))
  }, { id: owner, avatar: initialAvatar })
  return { records: () => documents, habits: () => habitData, metadata: () => userMetadata, offline: (value: boolean) => { offline = value }, conflict: () => { revision++ } }
}

